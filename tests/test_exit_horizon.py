"""Горизонт выхода выровнен со входом (16.09.2026).

Указание оператора: «ставка не на часы, а на недели».

Разрыв был тридцатикратным. Вход строится на EMA50/200 ДНЕВНЫХ свечей —
это недели-месяцы. Выход подтверждался тремя прогонами по два часа, то
есть шесть часов. Недельная идея закрывалась после полудня колебаний.

Что показали данные на 97 сделках:
  86% выходов — по смене вердикта, из них 44 в первые сутки
  стоп сработал 4 раза за всю историю: до него почти не доходит
  медиана удержания 24 часа, дольше недели — 7% сделок
  перебор моментума: лучшие наборы держали 20 дней

КРИТЕРИИ ОТКАТА, ЗАПИСАННЫЕ ДО ДАННЫХ:
  — медиана удержания не выросла до 3+ суток при n>=30 → выравнивание не
    сработало, причина в другом месте;
  — доля выходов по стопу выросла выше 40% → держим слишком долго, стоп
    стал основным выходом вместо страховки;
  — avg R упал ниже -0.15 при n>=30 → длинное удержание вредит, вернуть 2.
"""
import pytest

from src.position_guard import FLIP_CONFIRM_RUNS, POLICY_VERSION

RUNS_PER_DAY = 12          # гвард ходит раз в 2 часа


def test_confirmation_is_two_days():
    assert FLIP_CONFIRM_RUNS == 2 * RUNS_PER_DAY


def test_confirmation_is_far_shorter_than_working_window():
    """Двое суток — вдвое меньше самого короткого рабочего окна из
    перебора (лучшие наборы держали 20 дней). Выравниваем, а не
    перегибаем в другую сторону."""
    assert FLIP_CONFIRM_RUNS / RUNS_PER_DAY < 20 / 2


def test_confirmation_survives_a_full_day_of_noise():
    """44 выхода из 97 случились в первые сутки — их и надо пережить."""
    assert FLIP_CONFIRM_RUNS / RUNS_PER_DAY >= 1


def test_policy_version_bumped():
    """Выборки версий 2 и 3 нельзя складывать: это разные стратегии.
    Версия пишется в каждую exit-запись, чтобы статистика не смешалась."""
    assert POLICY_VERSION == 3


def test_stop_is_not_delayed():
    """Стоп остаётся немедленным: он про риск, а не про горизонт.
    Гистерезис применяется только к выходу по смене вердикта."""
    import inspect

    from src import position_guard

    src = inspect.getsource(position_guard)
    assert "sl_breach" in src
    # гистерезис упоминается рядом с verdict_flip, а не со стопом
    assert "FLIP_CONFIRM_RUNS" in src
